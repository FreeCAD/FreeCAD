# to run the example use:
"""
from femexamples.magnetization_3d import setup
setup()
"""


import FreeCAD

from BOPTools.SplitFeatures import makeBooleanFragments
from CompoundTools.CompoundFilter import makeCompoundFilter
import Materials
import ObjectsFem

from . import manager
from .meshes import generate_mesh


def get_information():
    return {
        "name": "Magnetization 3D",
        "meshtype": "solid",
        "meshelement": "Tet4",
        "constraints": ["electromagnetic", "magnetization"],
        "solvers": ["elmer"],
        "material": "solid",
        "equations": ["electromagnetic"],
    }


def get_explanation(header=""):
    return (
        header
        + """

To run the example from Python console use:
from femexamples.magnetization_3d import setup
setup()

Magnetodynamic equation - Elmer solver

Magnetic field generated by two magnetized cylinders

"""
    )


def setup(doc=None, solvertype="elmer"):

    # init FreeCAD document
    if doc is None:
        doc = manager.init_doc()

    # explanation object
    # just keep the following line and change text string in get_explanation method
    manager.add_explanation_obj(doc, get_explanation(manager.get_header(get_information())))

    # geometric objects

    # magnets
    magnet1 = doc.addObject("Part::Cylinder", "Magnet1")
    magnet1.Radius = "4 mm"
    magnet1.Height = "16 mm"
    magnet1.Placement.Base = FreeCAD.Vector(0, 0, 5)
    magnet1.ViewObject.Visibility = False

    magnet2 = doc.addObject("Part::Mirroring", "Magnet2")
    magnet2.Source = magnet1
    magnet2.Normal = FreeCAD.Vector(0, 0, 1)
    magnet2.Base = FreeCAD.Vector(0, 0, 0)
    magnet2.ViewObject.Visibility = False

    pair = doc.addObject("Part::Fuse", "Pair")
    pair.Base = magnet1
    pair.Tool = magnet2
    pair.ViewObject.Visibility = False

    # air around magnets
    sphere = doc.addObject("Part::Sphere", "Sphere")
    sphere.Radius = "50 mm"
    sphere.ViewObject.Visibility = False

    cut = doc.addObject("Part::Cut", "Space")
    cut.Base = sphere
    cut.Tool = pair
    cut.ViewObject.Visibility = False

    # boolean fragments object
    boolean_frag = makeBooleanFragments(name="BooleanFragments")
    boolean_frag.Objects = [cut, pair]
    boolean_frag.Mode = "CompSolid"
    boolean_frag.ViewObject.Visibility = False
    # compound filter object
    shape = makeCompoundFilter("CompoundFilter")
    shape.Base = boolean_frag
    shape.FilterType = "window-volume" 

    doc.recompute()

    # analysis
    analysis = ObjectsFem.makeAnalysis(doc, "Analysis")

    # set view
    if FreeCAD.GuiUp:
        shape.ViewObject.Transparency = 75
        shape.ViewObject.Document.activeView().viewAxonometric()
        shape.ViewObject.Document.activeView().fitAll()

        import FemGui
        FemGui.setActiveAnalysis(analysis)

    # solver
    if solvertype == "elmer":
        solver_obj = ObjectsFem.makeSolverElmer(doc, "SolverElmer")
        eq_mag = ObjectsFem.makeEquationMagnetodynamic(doc, solver_obj)
        eq_mag.BiCGstablDegree = 4
        eq_mag.IsHarmonic = False
        eq_mag.LinearIterativeMethod = "BiCGStabl"
        eq_mag.LinearPreconditioning = "None"
        eq_mag.CalculateMagneticFieldStrength = True
    else:
        FreeCAD.Console.PrintWarning(
            "Unknown or unsupported solver type: {}. "
            "No solver object was created.\n".format(solvertype)
        )
    analysis.addObject(solver_obj)

    # material
    mat_manager = Materials.MaterialManager()
    air = mat_manager.getMaterial("94370b96-c97e-4a3f-83b2-11d7461f7da7")
    air_obj = ObjectsFem.makeMaterialFluid(doc, "Air")
    air_obj.UUID = air.UUID
    air_obj.Material = air.Properties

    iron = mat_manager.getMaterial("1826c364-d26a-43fb-8f61-288281236836")
    iron_obj = ObjectsFem.makeMaterialFluid(doc, "Iron")
    iron_obj.UUID = iron.UUID
    iron_obj.Material = iron.Properties

    air_obj.References = [(shape, ("Solid1",))]
    iron_obj.References = [(shape, ("Solid2", "Solid3"))]
    analysis.addObject(air_obj)
    analysis.addObject(iron_obj)

    # outer potential vector A
    outer_potential = ObjectsFem.makeConstraintElectromagnetic(doc, "OuterPotential")
    outer_potential.References = [(shape, "Face1")]
    outer_potential.EnableAV_1 = True
    outer_potential.EnableAV_2 = True
    outer_potential.EnableAV_3 = True
    outer_potential.AV_re_1 = "0 Wb/m"
    outer_potential.AV_re_2 = "0 Wb/m"
    outer_potential.AV_re_3 = "0 Wb/m"
    analysis.addObject(outer_potential)

    # magnetization
    magnetization = ObjectsFem.makeConstraintMagnetization(doc, "Magnetization")
    magnetization.References = [(shape, ("Solid2", "Solid3"))]
    magnetization.Magnetization_re_3 = "5000.000 A/m"
    magnetization.EnableMagnetization_3 = True
    analysis.addObject(magnetization)

    # mesh
    femmesh_obj = analysis.addObject(ObjectsFem.makeMeshGmsh(doc, manager.get_meshname()))[0]
    femmesh_obj.Shape = shape
    femmesh_obj.ElementOrder = "1st"
    femmesh_obj.CharacteristicLengthMax = "5 mm"
    femmesh_obj.ViewObject.Visibility = False

    # mesh_region
    mesh_region = ObjectsFem.makeMeshRegion(doc, femmesh_obj, name="MeshRegion")
    mesh_region.CharacteristicLength = "0.75 mm"
    mesh_region.References = [(shape, ("Solid2", "Solid3"))]
    mesh_region.ViewObject.Visibility = False

    # generate the mesh
    generate_mesh.mesh_from_mesher(femmesh_obj, "gmsh")

    doc.recompute()

    return doc
