import FreeCAD
from types import SimpleNamespace
from typing import Any, Tuple, Mapping
from Path.Op.Util import drillTipLength
from .base import ToolBitShape


class ToolBitShapeDrill(ToolBitShape):
    name = "Drill"

    @classmethod
    def schema(cls) -> Mapping[str, Tuple[str, str]]:
        return {
            "CuttingEdgeHeight": (
                FreeCAD.Qt.translate("ToolBitShape", "Cutting edge height"),
                "App::PropertyLength",
            ),
            "Diameter": (
                FreeCAD.Qt.translate("ToolBitShape", "Diameter"),
                "App::PropertyLength",
            ),
            "Flutes": (
                FreeCAD.Qt.translate("ToolBitShape", "Flutes"),
                "App::PropertyInteger",
            ),
            "Length": (
                FreeCAD.Qt.translate("ToolBitShape", "Overall tool length"),
                "App::PropertyLength",
            ),
            "TipAngle": (
                FreeCAD.Qt.translate("ToolBitShape", "Tip angle"),
                "App::PropertyAngle",
            ),
        }

    @classmethod
    def derived_parameters(cls) -> Mapping[str, Any]:
        """Only the tip cone cuts sideways, so the cutting edge height is its length."""
        return {"CuttingEdgeHeight": lambda p: drillTipLength(SimpleNamespace(**p))}

    @property
    def label(self) -> str:
        return FreeCAD.Qt.translate("CAM", "Drill")
