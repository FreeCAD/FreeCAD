"""Topological-name handling for BRep shapes generated by Forms."""


def map_form_shape(_obj, shape, face_controls=None, source_shapes=()):
    """Return *shape* with FreeCAD's native operation history preserved.

    The BRep converter and OCCT Boolean operations already attach generated
    and modified-element history. Replacing that map with Python-authored names
    is unsafe because ``TopoShape`` element maps are copy-on-write and owner
    tagged. Only initialize a map when a producer returned a completely plain
    shape; otherwise leave its native history untouched.

    ``face_controls`` and ``source_shapes`` remain part of the call contract so
    surface and additive producers can use the same boundary function.
    """
    del face_controls, source_shapes
    if shape is None or shape.isNull() or shape.ElementMapSize:
        return shape
    faces = shape.Faces
    if faces:
        shape.mapSubElement(faces)
    return shape


__all__ = ["map_form_shape"]
