"""Topological-name handling for BRep shapes generated by Forms."""


def name_patch_face(face, face_id):
    """Seed a freshly generated patch with its logical cage/leaf identity.

    Do this before sewing, while the patch has exactly one face. Assigning a
    fresh map avoids mutating shared element maps; subsequent OCCT operations
    propagate this name through their history. T-mesh subdivision keeps the
    parent's ID on one child, so an attachment to the split face follows it.
    """
    face.ElementMap = {f"FormsFace{face_id}": "Face1"}
    return face


def map_form_shape(_obj, shape, face_controls=None, source_shapes=()):
    """Return *shape* with FreeCAD's native operation history preserved.

    Patch producers seed names before sewing. Keep the resulting sewing and
    Boolean history here: renaming the assembled shape would lose that history
    and confuse logical cage IDs with OCCT's output face order. Only initialize
    a map when a producer returned a completely plain shape.

    ``face_controls`` and ``source_shapes`` remain part of the call contract so
    surface and additive producers can use the same boundary function.
    """
    del face_controls, source_shapes
    if shape is None or shape.isNull() or shape.ElementMapSize:
        return shape
    faces = shape.Faces
    if faces:
        shape.mapSubElement(faces)
    return shape


__all__ = ["map_form_shape", "name_patch_face"]
