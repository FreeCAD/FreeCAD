"""Starlight-specific artifacts derived from the neutral public API model.

The Markdown emitter writes docs content in a Starlight-friendly directory
layout, but some sidebar polish still requires explicit config because
autogenerated directory labels cannot be renamed from frontmatter alone.

This module generates a small `sidebar.ts` fragment that a Starlight site can
import to expose the Python API tree with curated group labels such as
``Submodules`` and ``Types``.
"""

from __future__ import annotations

import json
from pathlib import Path

from .markdown import PYTHON_API_ROOT, child_modules, module_slug_parts
from .model import ApiClass, ApiModel, ApiModule


def module_slug(module_name: str) -> str:
    return "/".join((PYTHON_API_ROOT, *module_slug_parts(module_name)))


def class_slug(klass: ApiClass) -> str:
    return "/".join((module_slug(klass.module_name), "types", klass.name))


def page_link(slug: str) -> str:
    return f"/{slug}"


def module_group_label(module: ApiModule) -> str:
    return module.name.rsplit(".", 1)[-1]


def module_group_items(
    module: ApiModule, modules: tuple[ApiModule, ...]
) -> list[dict[str, object]]:
    items: list[dict[str, object]] = []
    submodules = child_modules(module.name, modules)
    if submodules:
        items.append(
            {
                "label": "Submodules",
                "items": [module_sidebar_group(child, modules) for child in submodules],
            }
        )
    if module.classes:
        items.append(
            {
                "label": "Types",
                "items": [
                    {"link": page_link(class_slug(klass)), "label": klass.name}
                    for klass in module.classes
                ],
            }
        )
    return items


def module_sidebar_group(
    module: ApiModule,
    modules: tuple[ApiModule, ...],
) -> dict[str, object]:
    items: list[dict[str, object]] = [
        {"link": page_link(module_slug(module.name)), "label": "Overview"}
    ]
    items.extend(module_group_items(module, modules))
    return {"label": module_group_label(module), "items": items}


def sidebar_items(model: ApiModel) -> list[dict[str, object]]:
    items: list[dict[str, object]] = [{"link": page_link(PYTHON_API_ROOT), "label": "Overview"}]
    for module in model.modules:
        if "." in module.name:
            continue
        items.append(module_sidebar_group(module, model.modules))
    return [{"label": "Python API", "items": items}]


def render_sidebar_fragment(model: ApiModel) -> str:
    items_json = json.dumps(sidebar_items(model), indent=2)
    return (
        "import type { StarlightSidebarUserConfig } from '@astrojs/starlight/types';\n\n"
        f"export const pythonApiSidebar: StarlightSidebarUserConfig = {items_json};\n"
    )


def write_starlight_sidebar_fragment(path: Path, model: ApiModel) -> Path:
    """Write the generated Starlight sidebar fragment."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_sidebar_fragment(model), encoding="utf-8")
    return path
